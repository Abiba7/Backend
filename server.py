# server.py
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from sqlalchemy import create_engine, Column, Integer, String
from sqlalchemy.orm import declarative_base, sessionmaker

app = FastAPI()

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)

DATABASE_URL = "sqlite:///./learners.db"
engine = create_engine(DATABASE_URL, connect_args={"check_same_thread": False})
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
Base = declarative_base()

class ScoreRecord(Base):
    __tablename__ = "scores"
    id = Column(Integer, primary_key=True, index=True)
    child_name = Column(String, index=True)
    score = Column(Integer)
    words_missed = Column(String)

Base.metadata.create_all(bind=engine)

class ScoreInput(BaseModel):
    child_name: str
    score: int
    words_missed: str

@app.get("/")
def home():
    return {"message": "Little Learners AI Backend is running with AI!"}

@app.post("/save-score")
def save_score(data: ScoreInput):
    db = SessionLocal()
    new_record = ScoreRecord(
        child_name=data.child_name,
        score=data.score,
        words_missed=data.words_missed
    )
    db.add(new_record)
    db.commit()
    db.refresh(new_record)
    db.close()
    return {"message": "Score saved successfully!", "record_id": new_record.id}

@app.get("/all-scores")
def get_scores():
    db = SessionLocal()
    scores = db.query(ScoreRecord).all()
    db.close()
    return scores

# --- NEW AI ROUTE ---
@app.get("/smart-practice")
def smart_practice():
    db = SessionLocal()
    scores = db.query(ScoreRecord).all()
    db.close()

    # 1. Gather every word the child has ever missed
    missed_counts = {}
    for record in scores:
        if record.words_missed:
            words = [w.strip() for w in record.words_missed.split(",") if w.strip()]
            for word in words:
                missed_counts[word] = missed_counts.get(word, 0) + 1

    # 2. Sort by the most missed
    weak_words = sorted(missed_counts.keys(), key=lambda w: missed_counts[w], reverse=True)

    # 3. Return the top 5 words to practice
    return {
        "message": "Smart practice generated by AI",
        "weak_words": weak_words[:5], 
        "all_stats": missed_counts
    }